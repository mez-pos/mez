// currencyExponents is money's exponent table as a TypeScript constant, so
// a frontend turns minor units into a displayed amount exactly as the server
// does. A yen shown as 12.34 when it means 1234 is the failure this prevents.
func currencyExponents() string {
	table := money.Exponents()
	codes := make([]string, 0, len(table))
	for code := range table {
		codes = append(codes, code)
	}
	slices.Sort(codes)

	var b strings.Builder
	b.WriteString("/** Decimal places of a currency's minor unit, where not the default. ISO 4217. */\n")
	b.WriteString("export const currencyExponents: Readonly<Record<string, number>> = {\n")
	for _, code := range codes {
		fmt.Fprintf(&b, "  %s: %d,\n", code, table[code])
	}
	b.WriteString("};\n\n")
	fmt.Fprintf(&b, "export const defaultCurrencyExponent = %d;\n", money.DefaultExponent)
	return b.String()
}

// asStrings is any list of named string constants as plain strings. It is
// not called strings, which would collide with the import in this package.
func asStrings[T ~string](values []T) []string {
	out := make([]string, len(values))
	for i, v := range values {
		out[i] = string(v)
	}
	return out
}

func paymentMethods() []string {
	return asStrings([]order.PaymentMethod{
		order.PaymentCash, order.PaymentCard, order.PaymentUPI, order.PaymentOther,
	})
}

func permissions() []string { return asStrings(auth.Permissions()) }

func eventTypeNames() []string {
	out := make([]string, len(eventTypes))
	for i, e := range eventTypes {
		out[i] = string(e.Type)
	}
	return out
}

// TestTypeScriptTypes generates web/shared/api-types.ts and fails if the
// committed file is not what the Go structs produce. With -update it writes
// the file instead, which is what `make generate` runs.
//
// This is the whole drift guard: `make check` runs the tests, so a struct
// changed without regenerating fails the build rather than reaching a
// frontend as a type that quietly lies.
func TestTypeScriptTypes(t *testing.T) {
	g, err := generate()
	if err != nil {
		t.Fatalf("generating: %v", err)
	}
	want := g.Source()

	if *update {
		if err := os.MkdirAll(filepath.Dir(typesFile), 0o750); err != nil {
			t.Fatalf("making the directory: %v", err)
		}
		if err := os.WriteFile(typesFile, []byte(want), 0o600); err != nil {
			t.Fatalf("writing %s: %v", typesFile, err)
		}
		t.Logf("wrote %s: %d declarations", typesFile, len(g.Names()))
		return
	}

	got, err := os.ReadFile(typesFile)
	if err != nil {
		t.Fatalf("%v\n\nRun `make generate` to write it.", err)
	}
	if string(got) != want {
		t.Errorf("%s is not what the Go structs generate.\n\nRun `make generate` and commit the result.\n%s",
			typesFile, firstDifference(string(got), want))
	}
}

// TestEveryEventTypeIsGenerated is what stops the hand-written union
// falling behind: the domain knows its own event types, and each one must
// appear here.
func TestEveryEventTypeIsGenerated(t *testing.T) {
	listed := map[order.Type]bool{}
	for _, e := range eventTypes {
		listed[e.Type] = true
		if got := e.Payload.(order.Payload).EventType(); got != e.Type {
			t.Errorf("%s is paired with a %s payload", e.Type, got)
		}
	}
	for _, typ := range order.Types() {
		if !listed[typ] {
			t.Errorf("event type %s is not in eventTypes, so TypeScript will not know it", typ)
		}
	}
}

// firstDifference points at the line that differs, since a whole-file diff
// in a test log is unreadable.
func firstDifference(got, want string) string {
	gotLines, wantLines := splitLines(got), splitLines(want)
	for i := range max(len(gotLines), len(wantLines)) {
		g, w := at(gotLines, i), at(wantLines, i)
		if g != w {
			return fmt.Sprintf("\nline %d:\n  committed: %q\n  generated: %q", i+1, g, w)
		}
	}
	return ""
}

func splitLines(s string) []string { return strings.Split(s, "\n") }

func at(lines []string, i int) string {
	if i < len(lines) {
		return lines[i]
	}
	return "(end of file)"
}
